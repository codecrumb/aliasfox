#!/usr/bin/env node
// Builds the public pages' stylesheet (landing, privacy, terms) with the Tailwind CLI:
//   pages/site.css  ->  ../src/aliasfox/page_templates/site.css   (committed, like hero3d.js)
//
//   node scripts/build-site.mjs           write the stylesheet
//   node scripts/build-site.mjs --check   exit 0 when the committed file is current, 3 when stale
//
// Tailwind's `/*! ... https://tailwindcss.com */` banner is replaced by a short header: the
// served CSS must contain no URLs at all (tests/test_pages.py asserts that).
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = join(web, 'pages/site.css');
const target = resolve(web, '../src/aliasfox/page_templates/site.css');
const HEADER = '/* GENERATED by web/scripts/build-site.mjs from web/pages/site.css. Do not edit. */\n';

const tmp = mkdtempSync(join(tmpdir(), 'aliasfox-site-'));
try {
  const out = join(tmp, 'site.css');
  const run = spawnSync(join(web, 'node_modules/.bin/tailwindcss'), ['-i', input, '-o', out, '--minify'], {
    cwd: web,
    encoding: 'utf8'
  });
  if (run.status !== 0) {
    process.stderr.write(run.stderr || String(run.error));
    process.exit(1);
  }
  const css = HEADER + readFileSync(out, 'utf8').replace(/^\/\*![\s\S]*?\*\/\n?/, '');
  if (/https?:\/\//.test(css)) {
    process.stderr.write('build-site: generated CSS contains a URL\n');
    process.exit(1);
  }
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== css) {
      process.stderr.write('site.css is stale: run `npm run build:site` in web/ and commit the result\n');
      process.exit(3);
    }
  } else {
    writeFileSync(target, css);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
